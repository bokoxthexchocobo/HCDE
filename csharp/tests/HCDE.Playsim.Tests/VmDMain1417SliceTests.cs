using HCDE.Playsim;
namespace HCDE.Playsim.Tests;
public class VmDMain1417SliceTests
{
    [Fact]
    public void StatusEpisodeAndSkill()
    {
        var quiet = new VmDMain1417Slice.State { Batch = true, Screen = true };
        VmDMain1417Slice.StartupStatusLine(quiet, "Loading", 1, true);
        Assert.Empty(quiet.Lines);
        Assert.Empty(quiet.Phases);
        var shown = new VmDMain1417Slice.State { Screen = true };
        VmDMain1417Slice.StartupStatusLine(shown, "Loading");
        Assert.Equal(new[] { "Loading\n" }, shown.Lines);
        Assert.Equal(new[] { "Loading" }, shown.Phases);
        var blind = new VmDMain1417Slice.State();
        VmDMain1417Slice.StartupStatusLine(blind, "Only the log");
        Assert.Equal(new[] { "Only the log\n" }, blind.Lines);
        Assert.Empty(blind.Phases);
        var batchVideo = new VmDMain1417Slice.State { Batch = true };
        VmDMain1417Slice.StartupPreVideoStatus(batchVideo, "hidden");
        Assert.Empty(batchVideo.Shown);
        Assert.Equal(new[] { "startup.prevideo hidden" }, batchVideo.Traces);
        var dedicated = new VmDMain1417Slice.State { Dedicated = true };
        VmDMain1417Slice.StartupPreVideoStatus(dedicated, null);
        Assert.Empty(dedicated.Shown);
        Assert.Equal(new[] { "startup.prevideo " }, dedicated.Traces);
        var video = new VmDMain1417Slice.State();
        VmDMain1417Slice.StartupPreVideoStatus(video, "Wads");
        Assert.Equal(new string?[] { "Wads" }, video.Shown);
        Assert.Equal(new[] { "startup.prevideo Wads" }, video.Traces);
        VmDMain1417Slice.StartupClearPreVideoStatus(video);
        VmDMain1417Slice.StartupClearPreVideoStatus(video);
        Assert.Equal(2, video.Clears);
        var none = new VmDMain1417Slice.State { Window = true, Screen = true };
        VmDMain1417Slice.StartupProgress(none, 0);
        VmDMain1417Slice.StartupProgress(none, -3);
        Assert.Empty(none.Steps);
        var both = new VmDMain1417Slice.State { Window = true, Screen = true };
        VmDMain1417Slice.StartupProgress(both, 4);
        Assert.Equal(new[] { ("window", 4), ("screen", 4) }, both.Steps);
        var window = new VmDMain1417Slice.State { Window = true };
        VmDMain1417Slice.StartupProgress(window, 1);
        Assert.Equal(new[] { ("window", 1) }, window.Steps);
        var picked = Episode("2");
        picked.Episodes.AddRange(new[] { "E1M1", "E2M1", "E3M1" });
        picked.SetMap = true;
        picked.StartMap = "MAP01";
        picked.FromLauncher = true;
        VmDMain1417Slice.CheckEpisodeCmd(picked);
        Assert.Equal("E2M1", picked.StartMap);
        Assert.True(picked.SetMap);
        Assert.True(picked.Autostart);
        Assert.False(picked.FromLauncher);
        Assert.Empty(picked.Lines);
        var invalid = Episode("99");
        invalid.Episodes.Add("E1M1");
        invalid.SetMap = true;
        invalid.StartMap = "MAP05";
        VmDMain1417Slice.CheckEpisodeCmd(invalid);
        Assert.Equal("MAP05", invalid.StartMap);
        Assert.False(invalid.Autostart);
        Assert.Equal(new[] { "Invalid episode 99\n" }, invalid.Lines);
        var fallback = Episode("abc");
        fallback.Episodes.AddRange(new[] { "E1M1", "E2M1" });
        VmDMain1417Slice.CheckEpisodeCmd(fallback);
        Assert.Equal("E1M1", fallback.StartMap);
        Assert.True(fallback.SetMap);
        Assert.False(fallback.Autostart);
        Assert.Equal(new[] { "Invalid episode abc\n" }, fallback.Lines);
        var launcher = new VmDMain1417Slice.State { SetMap = true, FromLauncher = true, StartMap = "MAP01" };
        launcher.Episodes.Add("E1M1");
        VmDMain1417Slice.CheckEpisodeCmd(launcher);
        Assert.Equal("E1M1", launcher.StartMap);
        Assert.False(launcher.FromLauncher);
        Assert.Equal(new[] { "HCDE: startup map MAP01 came from launcher default; using episode start map E1M1.\n" }, launcher.Lines);
        var same = new VmDMain1417Slice.State { SetMap = true, FromLauncher = true, StartMap = "e1m1" };
        same.Episodes.Add("E1M1");
        VmDMain1417Slice.CheckEpisodeCmd(same);
        Assert.Equal("e1m1", same.StartMap);
        Assert.True(same.FromLauncher);
        Assert.Empty(same.Lines);
        var blank = new VmDMain1417Slice.State { SetMap = true, FromLauncher = true, StartMap = "MAP01" };
        blank.Episodes.Add("");
        VmDMain1417Slice.CheckEpisodeCmd(blank);
        Assert.Equal("MAP01", blank.StartMap);
        Assert.True(blank.FromLauncher);
        var empty = new VmDMain1417Slice.State { SetMap = true, FromLauncher = true, StartMap = "MAP01" };
        VmDMain1417Slice.CheckEpisodeCmd(empty);
        Assert.Equal("MAP01", empty.StartMap);
        var held = new VmDMain1417Slice.State { SetMap = true, StartMap = "E3M1" };
        held.Episodes.Add("E1M1");
        VmDMain1417Slice.CheckEpisodeCmd(held);
        Assert.Equal("E3M1", held.StartMap);
        Assert.False(held.Autostart);
        var open = new VmDMain1417Slice.State();
        open.Episodes.Add("E1M1");
        VmDMain1417Slice.CheckEpisodeCmd(open);
        Assert.Equal("E1M1", open.StartMap);
        Assert.True(open.SetMap);
        Assert.False(open.Autostart);
        var skill = new VmDMain1417Slice.State { DefaultSkill = 3, SetSkill = 1 };
        VmDMain1417Slice.CheckDefaultSkill(skill);
        Assert.Equal(new[] { 3 }, skill.SkillDefaults);
        Assert.Equal(1, skill.Skill);
        var untouched = new VmDMain1417Slice.State();
        VmDMain1417Slice.CheckDefaultSkill(untouched);
        Assert.Empty(untouched.SkillDefaults);
        Assert.Null(untouched.Skill);
        var failed = Assert.Throws<InvalidOperationException>(VmDMain1417Slice.NewFailure);
        Assert.Equal("Failed to allocate memory from system heap", failed.Message);
    }
    [Fact]
    public void SpriteAndFontRenames()
    {
        var doom = Names(VmDMain1417Slice.Doom, "DBIGFONT");
        doom.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Sprites, 0, "HEADA0A0"));
        doom.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Sprites, 0, "BLODA0A0"));
        doom.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Sprites, 2, "BLODB0B0"));
        VmDMain1417Slice.RenameSprites(doom.State, doom.Lumps, doom.Remove);
        Assert.Equal("BIGFONT", doom.Lumps[0].Name);
        Assert.Equal("HEADA0A0", doom.Lumps[1].Name);
        Assert.Equal("BLODA0A0", doom.Lumps[2].Name);
        Assert.Equal("BLODB0B0", doom.Lumps[3].Name);
        var heretic = Names(VmDMain1417Slice.Heretic, "HBIGFONT");
        heretic.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Sprites, 0, "HEADA0"));
        heretic.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Sprites, 4, "HEADB0"));
        heretic.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Sprites, 4, "BLODC0"));
        VmDMain1417Slice.RenameSprites(heretic.State, heretic.Lumps, heretic.Remove);
        Assert.Equal("BIGFONT", heretic.Lumps[0].Name);
        Assert.Equal("LICHA0", heretic.Lumps[1].Name);
        Assert.Equal("HEADB0", heretic.Lumps[2].Name);
        Assert.Equal("BLUDC0", heretic.Lumps[3].Name);
        var forced = Names(VmDMain1417Slice.Heretic, "HBIGFONT");
        forced.State.NoSpriteRename = true;
        forced.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Sprites, 9, "HEADF0"));
        forced.State.Args.Add("-oldsprites");
        VmDMain1417Slice.RenameSprites(forced.State, forced.Lumps, forced.Remove);
        Assert.Equal("LICHF0", forced.Lumps[1].Name);
        var hexen = Names(VmDMain1417Slice.Hexen, "HBIGFONT");
        hexen.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Sprites, 0, "BARLA0A0"));
        hexen.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Sprites, 0, "INVUA0A0"));
        hexen.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Sprites, 0, "ArTiInVu"));
        hexen.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Sprites, 3, "ARTIINVU"));
        hexen.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Sprites, 0, "BLODX0"));
        VmDMain1417Slice.RenameSprites(hexen.State, hexen.Lumps, hexen.Remove);
        Assert.Equal("BIGFONT", hexen.Lumps[0].Name);
        Assert.Equal("ZBARA0A0", hexen.Lumps[1].Name);
        Assert.Equal("DEFNA0A0", hexen.Lumps[2].Name);
        Assert.Equal("ArTiDEFN", hexen.Lumps[3].Name);
        Assert.Equal("ARTIINVU", hexen.Lumps[4].Name);
        Assert.Equal("BLUDX0", hexen.Lumps[5].Name);
        var strife = Names(VmDMain1417Slice.Strife, "SBIGFONT");
        strife.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Sprites, 0, "MISLA0A0"));
        strife.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Sprites, 0, "MNTRZ0A0"));
        strife.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Sprites, 0, "MNTRF0K0"));
        VmDMain1417Slice.RenameSprites(strife.State, strife.Lumps, strife.Remove);
        Assert.Equal("BIGFONT", strife.Lumps[0].Name);
        Assert.Equal("SMISA0A0", strife.Lumps[1].Name);
        Assert.Equal("MNTRZ0A0", strife.Lumps[2].Name);
        Assert.Equal("MNTRF0K0", strife.Lumps[3].Name);
        var shifted = Names(VmDMain1417Slice.Doom, "DBIGFONT");
        shifted.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Sprites, 5, "MNTRF0K0"));
        shifted.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Sprites, 5, "MNTRE0L0"));
        VmDMain1417Slice.RenameSprites(shifted.State, shifted.Lumps, shifted.Remove);
        Assert.Equal("MNTRU0Z0", shifted.Lumps[1].Name);
        Assert.Equal("MNTRE0L0", shifted.Lumps[2].Name);
        var chex = Names(VmDMain1417Slice.DoomChex, "DBIGFONT");
        chex.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Sprites, 0, "HEADA0"));
        chex.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Sprites, 0, "BLODA0"));
        VmDMain1417Slice.RenameSprites(chex.State, chex.Lumps, chex.Remove);
        Assert.Equal("HEADA0", chex.Lumps[1].Name);
        Assert.Equal("BLODA0", chex.Lumps[2].Name);
        var raven = Names(VmDMain1417Slice.Raven, "HBIGFONT");
        raven.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Sprites, 0, "BLODA0"));
        raven.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Sprites, 0, "HEADA0"));
        VmDMain1417Slice.RenameSprites(raven.State, raven.Lumps, raven.Remove);
        Assert.Equal("BIGFONT", raven.Lumps[0].Name);
        Assert.Equal("BLUDA0", raven.Lumps[1].Name);
        Assert.Equal("HEADA0", raven.Lumps[2].Name);
        var deleted = Names(VmDMain1417Slice.Doom, "DBIGFONT");
        deleted.Remove.Add("DEMO");
        deleted.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Global, 0, "DEMO"));
        deleted.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Global, 2, "DEMO"));
        deleted.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Global, 3, "DEMO"));
        deleted.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Sprites, 0, "DBIGFONT"));
        VmDMain1417Slice.RenameSprites(deleted.State, deleted.Lumps, deleted.Remove);
        Assert.Equal("BIGFONT", deleted.Lumps[0].Name);
        Assert.Equal("", deleted.Lumps[1].Name);
        Assert.Equal("", deleted.Lumps[2].Name);
        Assert.Equal("DEMO", deleted.Lumps[3].Name);
        Assert.Equal("DBIGFONT", deleted.Lumps[4].Name);
        var eaten = Names(VmDMain1417Slice.Doom, "DBIGFONT");
        eaten.Remove.Add("DBIGFONT");
        VmDMain1417Slice.RenameSprites(eaten.State, eaten.Lumps, eaten.Remove);
        Assert.Equal("", eaten.Lumps[0].Name);
        var flagged = Names(VmDMain1417Slice.Hexen, "HBIGFONT");
        flagged.State.Args.Add("-OLDSPRITES");
        flagged.Lumps.Add(new VmDMain1417Slice.Lump(VmDMain1417Slice.Sprites, 8, "ARTIINVU"));
        VmDMain1417Slice.RenameSprites(flagged.State, flagged.Lumps, flagged.Remove);
        Assert.Equal("ARTIDEFN", flagged.Lumps[1].Name);
    }
    static VmDMain1417Slice.State Episode(params string[] args)
    {
        var state = new VmDMain1417Slice.State();
        state.Args.Add("-episode");
        state.Args.AddRange(args);
        return state;
    }
    static (VmDMain1417Slice.State State, List<VmDMain1417Slice.Lump> Lumps, List<string> Remove) Names(int game, string font)
    {
        var state = new VmDMain1417Slice.State { GameType = game, Iwad = 0, MaxIwad = 2 };
        var lumps = new List<VmDMain1417Slice.Lump> { new(VmDMain1417Slice.Global, 1, font) };
        return (state, lumps, new List<string>());
    }
