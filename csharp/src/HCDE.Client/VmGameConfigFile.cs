namespace HCDE.Client;

/// <summary>Managed <c>FGameConfigFile</c> bootstrap from <c>gameconfigfile.cpp</c>.</summary>
public sealed class VmGameConfigFile : VmConfigFile
{
    public VmGameConfigFile(IReadOnlyList<string> defaultSearchPaths, string? existingIni = null)
    {
        OkayToWrite = false;
        if (existingIni is not null) LoadFromText(existingIni);
        var last = GetLastRunVersion();
        VmGameConfigLastRun227.EnsureSearchPathsForLegacyConfig(this, last, defaultSearchPaths);
        EnsureDefaultSearchSections(defaultSearchPaths);
    }

    public static IReadOnlyList<string> CollectDefaultSearchPaths(string progDir, string? homeDir)
    {
        var paths = new List<string>();
        if (!string.IsNullOrEmpty(homeDir)) paths.Add("$HOME");
        paths.Add("$PROGDIR");
        if (OperatingSystem.IsLinux() && !string.IsNullOrEmpty(progDir))
        {
            paths.Add(progDir);
            paths.Add("/usr/local/share/gzdoom");
        }

        return paths;
    }

    public string WriteGameHeader(string version, string timestamp) =>
        $"# This file was generated by HCDE {version} on {timestamp}\n";

    public void ApplyLegacyGammaMigration(float legacyGamma, Action<float> setFixGamma)
    {
        setFixGamma(VmGameConfigLegacyGamma.LegacyGammaToFixGamma(legacyGamma));
    }

    public void DoGlobalSetup(IDictionary<string, string> cvars, string currentVersion)
    {
        VmGameConfigCvars.ReadGlobalSettings(this, cvars);
        var last = GetLastRunVersion();
        if (SetSection("LastRun") && VmGameConfigGlobalSetup.IsNewRelease(GetValueForKey("Release"), currentVersion))
            cvars["i_is_new_release"] = "true";
        VmGameConfigGlobalSetup.PurgeWeaponSlotSections(this, last);
        VmGameConfigGlobalSetup.ApplyHexenBindingFix(this, last);
        VmGameConfigVersionMigrations.Apply(last, cvars);
        var flags = ResetBindFlags;
        VmGameConfigResetBindFlags.QueueFromLastRunVersion(last, ref flags);
        ResetBindFlags = flags;
    }

    public int ResetBindFlags { get; set; }

    public void DoGameSetup(string gameName, IDictionary<string, string> cvars)
    {
        VmGameConfigGameSetup.ReadGameCvarSections(this, gameName, cvars);
        VmGameConfigGameSetup.ApplyHcdeUiBaseline(GetLastRunVersion(), cvars);
    }

    public void DoKeySetup(
        string gameName,
        VmKeyBindings bindings,
        VmKeyBindings doubleBindings,
        VmKeyBindings automapBindings,
        Action? resetJoysticks = null,
        IReadOnlyList<int>? axisKeysToReset = null)
    {
        var flags = ResetBindFlags;
        VmGameConfigKeySetup.DoKeySetup(this, gameName, bindings, doubleBindings, automapBindings, ref flags, resetJoysticks, axisKeysToReset);
        ResetBindFlags = flags;
    }

    public bool DoModSetup(string gameName, IDictionary<string, string> sink) =>
        VmGameConfigModSetup.DoModSetup(this, gameName, sink);

    public void ReadNetVars(string gameName, IDictionary<string, string> sink, bool modSetup) =>
        VmGameConfigModSetup.ReadNetVars(this, gameName, sink, modSetup);

    public void DoAutoloadSetup(IEnumerable<string> iwadAutonames)
    {
        var last = GetLastRunVersion();
        VmGameConfigAutoload.ApplyLegacyRenames(this, last);
        VmGameConfigAutoload.EnsureAutoloadHierarchy(this, iwadAutonames);
        VmGameConfigAutoload.CreateStandardAutoExec(this, "Doom.AutoExec", "autoexec.cfg", moveToStart: true);
        MoveSectionToStart("SoundfontSearch.Directories");
        MoveSectionToStart("FileSearch.Directories");
        MoveSectionToStart("IWADSearch.Directories");
    }

    public IReadOnlyList<string> AddAutoexec(string game, Func<string, bool> fileExists)
    {
        VmGameConfigAutoload.CreateStandardAutoExec(this, $"{game}.AutoExec", "autoexec.cfg", moveToStart: false);
        return VmGameConfigAutoload.CollectAutoexecPaths(this, game, fileExists);
    }

    private double GetLastRunVersion()
    {
        if (!SetSection("LastRun")) return 0;
        var lastver = GetValueForKey("Version");
        return double.TryParse(lastver, out var last) ? last : 0;
    }

    private void EnsureDefaultSearchSections(IReadOnlyList<string> defaultSearchPaths)
    {
        if (!SetSection("IWADSearch.Directories"))
        {
            SetSection("IWADSearch.Directories", allowCreate: true);
            SetValueForKey("Path", ".", duplicates: true);
            SetValueForKey("Path", "$DOOMWADDIR", duplicates: true);
            SetValueForKey("PathList", "$DOOMWADPATH", duplicates: true);
            foreach (var path in defaultSearchPaths) SetValueForKey("Path", path, duplicates: true);
        }

        if (!SetSection("FileSearch.Directories"))
        {
            SetSection("FileSearch.Directories", allowCreate: true);
            SetValueForKey("Path", "$DOOMWADDIR", duplicates: true);
            SetValueForKey("PathList", "$DOOMWADPATH", duplicates: true);
            foreach (var path in defaultSearchPaths) SetValueForKey("Path", path, duplicates: true);
        }

        if (!SetSection("SoundfontSearch.Directories"))
        {
            SetSection("SoundfontSearch.Directories", allowCreate: true);
            foreach (var path in defaultSearchPaths)
            {
                SetValueForKey("Path", $"{path}/soundfonts", duplicates: true);
                SetValueForKey("Path", $"{path}/fm_banks", duplicates: true);
            }
        }
    }
}
